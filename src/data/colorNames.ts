export function hexToSlug(name: string, hex: string): string {
  const cleanHex = hex.replace('#', '').toLowerCase();
  const cleanName = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)+/g, '');
  return `${cleanName}-${cleanHex}`;
}

export function parseSlug(slug: string): { name: string; hex: string } | null {
  const parts = slug.split('-');
  const hexPart = parts[parts.length - 1];
  if (/^[0-9a-fA-F]{6}$/.test(hexPart) || /^[0-9a-fA-F]{3}$/.test(hexPart)) {
    const rawName = parts.slice(0, parts.length - 1).join(' ');
    const formattedName = rawName
      .split(' ')
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(' ');
    return {
      name: formattedName || 'Color',
      hex: `#${hexPart.toLowerCase()}`,
    };
  }
  return null;
}

